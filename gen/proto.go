package main

import (
	"fmt"
	"sort"
	"strings"
	"unicode"
)

// protoScalars maps spec scalar types to proto3 scalar types.
var protoScalars = map[string]string{
	"bool": "bool", "int32": "int32", "int64": "int64",
	"uint32": "uint32", "uint64": "uint64", "string": "string", "bytes": "bytes",
}

// genProto renders the wire messages and enums as a proto3 file. Field numbers
// come straight from the spec. Operation shapes given inline become
// <Op>Request and <Op>Response messages. Operations that reference a named
// message keep that name.
func genProto(s *Spec, pkg, goPkg string) string {
	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by mountos-native-sdk gen. DO NOT EDIT.\n\n")
	b.WriteString("syntax = \"proto3\";\n\n")
	fmt.Fprintf(&b, "package %s;\n\n", pkg)
	fmt.Fprintf(&b, "option go_package = %q;\n\n", goPkg)

	for _, name := range sortedKeys(s.Enums) {
		e := s.Enums[name]
		fmt.Fprintf(&b, "enum %s {\n", name)
		prefix := snakeUpper(name)
		values := sortedEnumValues(e.Values)
		for _, v := range values {
			fmt.Fprintf(&b, "  %s_%s = %d;\n", prefix, v.name, v.num)
		}
		b.WriteString("}\n\n")
	}

	msgs := map[string]map[string]Field{}
	for name, fields := range s.Messages {
		msgs[name] = fields
	}
	for _, op := range s.Operations {
		if op.Request.Ref == "" {
			msgs[op.Name+"Request"] = op.Request.Fields
		}
		if op.Response.Ref == "" {
			msgs[op.Name+"Response"] = op.Response.Fields
		}
	}
	for _, name := range sortedKeys(msgs) {
		fmt.Fprintf(&b, "message %s {\n", name)
		fields := msgs[name]
		names := sortedFieldNames(fields)
		for _, fname := range names {
			f := fields[fname]
			fmt.Fprintf(&b, "  %s %s = %d;\n", protoType(f.Type), fname, f.ID)
		}
		b.WriteString("}\n\n")
	}
	return b.String()
}

// protoType maps a spec type (with optional `repeated` prefix) to proto3.
func protoType(t string) string {
	t = strings.TrimSpace(t)
	if rest, ok := strings.CutPrefix(t, "repeated "); ok {
		return "repeated " + protoType(rest)
	}
	if p, ok := protoScalars[t]; ok {
		return p
	}
	return t
}

// snakeUpper turns OpenFlag into OPEN_FLAG. Enum value names are prefixed with
// it because proto3 enum values share the package scope.
func snakeUpper(name string) string {
	var out []rune
	for i, r := range name {
		if i > 0 && unicode.IsUpper(r) {
			out = append(out, '_')
		}
		out = append(out, unicode.ToUpper(r))
	}
	return string(out)
}

type enumValue struct {
	name string
	num  int
}

func sortedEnumValues(m map[string]int) []enumValue {
	out := make([]enumValue, 0, len(m))
	for n, v := range m {
		out = append(out, enumValue{n, v})
	}
	sort.Slice(out, func(i, j int) bool { return out[i].num < out[j].num })
	return out
}

func sortedFieldNames(m map[string]Field) []string {
	names := make([]string, 0, len(m))
	for n := range m {
		names = append(names, n)
	}
	sort.Slice(names, func(i, j int) bool { return m[names[i]].ID < m[names[j]].ID })
	return names
}
