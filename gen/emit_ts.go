package main

import (
	"bytes"
	"fmt"
	"strings"
)

func init() {
	emitters = append(emitters, emitter{
		flag: "ts-out",
		desc: "write the generated TypeScript client stubs (ops_gen.ts) into this directory",
		file: "ops_gen.ts",
		emit: emitTS,
	})
}

// tsScalar maps a spec scalar to a TypeScript type. 64-bit integers are bigint
// only when big is true, because most of them are sizes and counts that fit a
// number below 2^53.
func tsScalar(t string, big bool) (string, bool) {
	switch t {
	case "string":
		return "string", true
	case "bool":
		return "boolean", true
	case "bytes":
		return "Uint8Array", true
	case "int32", "uint32":
		return "number", true
	case "int64", "uint64":
		if big {
			return "bigint", true
		}
		return "number", true
	}
	return "", false
}

// tsParamType gives the public type of a request parameter. Times (names that
// end in _ns) stay bigint. Other 64-bit parameters are numbers.
func tsParamType(s *Spec, p StubField) (string, error) {
	if _, ok := s.Enums[p.Type]; ok {
		return "number", nil
	}
	if t, ok := tsScalar(p.Type, strings.HasSuffix(p.Name, "_ns")); ok {
		return t, nil
	}
	return "", fmt.Errorf("parameter %s has unsupported type %s", p.Name, p.Type)
}

// tsReturnType gives the public type of one response field. Fields of a result
// interface keep full 64-bit width. A lone 64-bit return is a count and becomes
// a number.
func tsReturnType(s *Spec, r StubField, inResult bool) (string, error) {
	if _, ok := s.Enums[r.Type]; ok {
		return "number", nil
	}
	if r.Type == "FileInfo" {
		return "FileInfo", nil
	}
	if t, ok := tsScalar(r.Type, inResult); ok {
		return t, nil
	}
	return "", fmt.Errorf("response field %s has unsupported type %s", r.Name, r.Type)
}

func is64(t string) bool { return t == "int64" || t == "uint64" }

// emitTS renders the method ids, result interfaces, and one abstract base class
// per scope. The hand-written Client and FileHandle extend these classes and
// supply the call function.
func emitTS(s *Spec, stubs []Stub) ([]byte, error) {
	var body bytes.Buffer
	needInfo := false
	scopes := []string{"client", "file", "dir"}
	classes := map[string]string{"client": "ClientOps", "file": "FileOps", "dir": "DirOps"}

	for _, st := range stubs {
		if !st.Emit {
			continue
		}
		if err := writeTSResult(&body, s, st); err != nil {
			return nil, fmt.Errorf("%s: %w", st.Op.Name, err)
		}
	}
	for _, scope := range scopes {
		var methods bytes.Buffer
		for _, st := range stubs {
			if !st.Emit || st.Scope != scope {
				continue
			}
			if err := writeTSStub(&methods, s, st, &needInfo); err != nil {
				return nil, fmt.Errorf("%s: %w", st.Op.Name, err)
			}
		}
		if methods.Len() == 0 {
			continue
		}
		fmt.Fprintf(&body, "/** Generated %s operations. The subclass supplies call. */\nexport abstract class %s {\n", scope, classes[scope])
		body.WriteString("  protected abstract call(method: number, meta: Buffer): Promise<Buffer>;\n")
		if scope != "client" {
			body.WriteString("  protected abstract readonly id: bigint;\n")
		}
		body.WriteString("\n")
		body.Write(bytes.TrimRight(methods.Bytes(), "\n"))
		body.WriteString("\n}\n\n")
	}

	var b bytes.Buffer
	b.WriteString("// Code generated by mountos-native-sdk gen from api/filesystem.yaml and api/client.yaml. DO NOT EDIT.\n\n")
	if needInfo {
		b.WriteString("import { dec, enc, statInfo } from \"./api.js\";\nimport type { FileInfo } from \"./api.js\";\n")
	} else {
		b.WriteString("import { dec, enc } from \"./api.js\";\n")
	}
	b.WriteString("import * as pb from \"./gen/mountos_fs.js\";\n\n")

	b.WriteString("/** Method IDs from api/filesystem.yaml. */\nexport const Method = {\n")
	for _, op := range s.Operations {
		fmt.Fprintf(&b, "  %s: %d,\n", op.Name, op.ID)
	}
	b.WriteString("} as const;\n\n")
	b.Write(bytes.TrimRight(body.Bytes(), "\n"))
	b.WriteString("\n")
	return b.Bytes(), nil
}

func writeTSResult(b *bytes.Buffer, s *Spec, st Stub) error {
	if st.Result == "" {
		return nil
	}
	fmt.Fprintf(b, "/** Result of %s. */\nexport interface %s {\n", lowerCamel(st.Name), st.Result)
	for _, r := range st.Returns {
		if r.Type == "FileInfo" {
			return fmt.Errorf("message field %s is not supported in a result interface", r.Name)
		}
		t, err := tsReturnType(s, r, true)
		if err != nil {
			return err
		}
		fmt.Fprintf(b, "  %s: %s;\n", lowerCamel(r.Name), t)
	}
	b.WriteString("}\n\n")
	return nil
}

func writeTSStub(b *bytes.Buffer, s *Spec, st Stub, needInfo *bool) error {
	params := make([]string, 0, len(st.Params))
	fields := make([]string, 0, len(st.Params)+1)
	if st.Scope != "client" {
		fields = append(fields, "handle: this.id")
	}
	for _, p := range st.Params {
		t, err := tsParamType(s, p)
		if err != nil {
			return err
		}
		name := lowerCamel(p.Name)
		sig := fmt.Sprintf("%s: %s", name, t)
		if def, ok := st.Defaults[p.Name]; ok {
			sig = fmt.Sprintf("%s = %d", name, def)
		}
		params = append(params, sig)
		if is64(p.Type) && t == "number" {
			fields = append(fields, fmt.Sprintf("%s: BigInt(%s)", name, name))
		} else {
			fields = append(fields, name)
		}
	}

	req := "Buffer.alloc(0)"
	if st.ReqMsg != "Empty" {
		req = fmt.Sprintf("enc(pb.%s, { %s })", st.ReqMsg, strings.Join(fields, ", "))
	}
	call := fmt.Sprintf("this.call(Method.%s, %s)", st.Op.Name, req)

	fmt.Fprintf(b, "  /** %s */\n", st.Doc)
	name := lowerCamel(st.Name)
	switch {
	case len(st.Returns) == 0:
		fmt.Fprintf(b, "  async %s(%s): Promise<void> {\n    await %s;\n  }\n\n", name, strings.Join(params, ", "), call)
	case len(st.Returns) == 1:
		r := st.Returns[0]
		t, err := tsReturnType(s, r, false)
		if err != nil {
			return err
		}
		field := "r." + lowerCamel(r.Name)
		switch {
		case r.Type == "FileInfo":
			*needInfo = true
			field = fmt.Sprintf("statInfo(%s)", field)
		case is64(r.Type):
			field = fmt.Sprintf("Number(%s)", field)
		}
		fmt.Fprintf(b, "  async %s(%s): Promise<%s> {\n    const r = dec(pb.%s, await %s);\n    return %s;\n  }\n\n",
			name, strings.Join(params, ", "), t, st.RespMsg, call, field)
	default:
		parts := make([]string, 0, len(st.Returns))
		for _, r := range st.Returns {
			parts = append(parts, fmt.Sprintf("%s: r.%s", lowerCamel(r.Name), lowerCamel(r.Name)))
		}
		fmt.Fprintf(b, "  async %s(%s): Promise<%s> {\n    const r = dec(pb.%s, await %s);\n    return { %s };\n  }\n\n",
			name, strings.Join(params, ", "), st.Result, st.RespMsg, call, strings.Join(parts, ", "))
	}
	return nil
}
