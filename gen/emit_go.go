package main

import (
	"bytes"
	"fmt"
	"go/format"
	"strings"
)

func init() {
	emitters = append(emitters, emitter{
		flag: "go-out",
		desc: "write the generated Go client stubs (ops_gen.go) into this directory",
		file: "ops_gen.go",
		emit: emitGo,
	})
}

// goType maps a spec type to the Go type used in generated stubs.
func goType(s *Spec, t string) string {
	t = strings.TrimSpace(t)
	if rest, ok := strings.CutPrefix(t, "repeated "); ok {
		return "[]" + goType(s, rest)
	}
	switch t {
	case "bytes":
		return "[]byte"
	case "bool", "int32", "int64", "uint32", "uint64", "string":
		return t
	}
	if _, ok := s.Enums[t]; ok {
		return "wire." + t
	}
	return "*wire." + t
}

// goZero returns a literal that is the zero value of a Go type.
func goZero(gt string) string {
	switch {
	case gt == "string":
		return `""`
	case gt == "bool":
		return "false"
	case strings.HasPrefix(gt, "*"), strings.HasPrefix(gt, "[]"):
		return "nil"
	default:
		return "0"
	}
}

// emitGo renders the method constants, result structs, and operation stubs for
// the Go client. Custom and planned operations only get a constant.
func emitGo(s *Spec, stubs []Stub) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("// Code generated by mountos-native-sdk gen from api/filesystem.yaml and api/client.yaml. DO NOT EDIT.\n\n")
	b.WriteString("package client\n\nimport \"github.com/mountos-io/mountos-native-sdk/go/wire\"\n\n")

	b.WriteString("// Method IDs from the API spec.\nconst (\n")
	for _, op := range s.Operations {
		fmt.Fprintf(&b, "\tm%s uint16 = %d\n", op.Name, op.ID)
	}
	b.WriteString(")\n\n")

	for _, st := range stubs {
		if !st.Emit {
			continue
		}
		writeGoResult(&b, s, st)
		writeGoStub(&b, s, st)
	}
	out, err := format.Source(b.Bytes())
	if err != nil {
		return b.Bytes(), fmt.Errorf("format generated Go: %w", err)
	}
	return out, nil
}

func writeGoResult(b *bytes.Buffer, s *Spec, st Stub) {
	if st.Result == "" {
		return
	}
	fmt.Fprintf(b, "// %s is the result of %s.\ntype %s struct {\n", st.Result, st.Name, st.Result)
	for _, r := range st.Returns {
		fmt.Fprintf(b, "\t%s %s\n", upperCamel(r.Name), goType(s, r.Type))
	}
	b.WriteString("}\n\n")
}

func writeGoStub(b *bytes.Buffer, s *Spec, st Stub) {
	params := make([]string, 0, len(st.Params))
	fields := make([]string, 0, len(st.Params)+1)
	if st.Scope != "client" {
		fields = append(fields, "Handle: f.handle")
	}
	for _, p := range st.Params {
		params = append(params, fmt.Sprintf("%s %s", lowerCamel(p.Name), goType(s, p.Type)))
		fields = append(fields, fmt.Sprintf("%s: %s", upperCamel(p.Name), lowerCamel(p.Name)))
	}
	req := "&wire.Empty{}"
	if st.ReqMsg != "Empty" {
		req = fmt.Sprintf("&wire.%s{%s}", st.ReqMsg, strings.Join(fields, ", "))
	}

	// Result type and the expression that builds it from the response.
	retSig, retExpr, zero := "error", "", ""
	switch {
	case len(st.Returns) == 1:
		gt := goType(s, st.Returns[0].Type)
		retSig = fmt.Sprintf("(%s, error)", gt)
		retExpr = fmt.Sprintf("r.Get%s()", upperCamel(st.Returns[0].Name))
		zero = goZero(gt)
	case len(st.Returns) > 1:
		retSig = fmt.Sprintf("(*%s, error)", st.Result)
		parts := make([]string, 0, len(st.Returns))
		for _, r := range st.Returns {
			parts = append(parts, fmt.Sprintf("%s: r.Get%s()", upperCamel(r.Name), upperCamel(r.Name)))
		}
		retExpr = fmt.Sprintf("&%s{%s}", st.Result, strings.Join(parts, ", "))
		zero = "nil"
	}

	recv := "cl *Client"
	if st.Scope != "client" {
		recv = "f *File"
	}
	fmt.Fprintf(b, "// %s %s\nfunc (%s) %s(%s) %s {\n", st.Name, lowerFirst(st.Doc), recv, st.Name, strings.Join(params, ", "), retSig)

	resp := "&wire.Empty{}"
	if len(st.Returns) > 0 {
		resp = "&r"
		fmt.Fprintf(b, "\tvar r wire.%s\n", st.RespMsg)
	}
	call := fmt.Sprintf("cl.run(m%s, %s, %s)", st.Op.Name, req, resp)
	if st.Scope != "client" {
		b.WriteString("\tf.mu.Lock()\n\tdefer f.mu.Unlock()\n")
		call = fmt.Sprintf("f.do(m%s, %s, %s, nil)", st.Op.Name, req, resp)
	}

	switch {
	case len(st.Returns) == 0 && st.Scope == "client":
		fmt.Fprintf(b, "\treturn %s\n}\n\n", call)
	case len(st.Returns) == 0:
		fmt.Fprintf(b, "\t_, err := %s\n\treturn err\n}\n\n", call)
	case st.Scope == "client":
		fmt.Fprintf(b, "\tif err := %s; err != nil {\n\t\treturn %s, err\n\t}\n\treturn %s, nil\n}\n\n", call, zero, retExpr)
	default:
		fmt.Fprintf(b, "\tif _, err := %s; err != nil {\n\t\treturn %s, err\n\t}\n\treturn %s, nil\n}\n\n", call, zero, retExpr)
	}
}
